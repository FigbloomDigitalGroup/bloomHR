interface EmojiPickerProps {
  onEmojiSelect: (emoji: string) => void;
  children: React.ReactNode;
  open?: boolean;
  onOpenChange?: (open: boolean) => void;
}

export function EmojiPicker({ onEmojiSelect, children, open, onOpenChange }: EmojiPickerProps) {
  return (
    <Popover open={open} onOpenChange={onOpenChange}>
      <PopoverTrigger asChild>
        {children}
      </PopoverTrigger>
      <PopoverContent className="w-80 p-0 bg-background">
        <div className="max-h-60 overflow-y-auto">
          {Object.entries(emojiCategories).map(([category, emojis]) => (
            <div key={category} className="border-b last:border-b-0">
              {/* Fixed: Added solid background to category header */}
              <div className="text-xs font-medium text-muted-foreground px-3 py-2 bg-background sticky top-0 border-b backdrop-blur-sm z-10">
                {category}
              </div>
              <div className="grid grid-cols-8 gap-1 p-2">
                {emojis.map((emoji) => (
                  <Button
                    key={emoji}
                    variant="ghost"
                    className="h-8 w-8 p-0 text-lg hover:bg-muted transition-colors"
                    onClick={() => onEmojiSelect(emoji)}
                    type="button"
                  >
                    <span className="inline-block leading-none" style={{ fontFamily: "'Segoe UI Emoji', 'Apple Color Emoji', 'Noto Color Emoji', sans-serif" }}>
                      {emoji}
                    </span>
                  </Button>
                ))}
              </div>
            </div>
          ))}
        </div>
      </PopoverContent>
    </Popover>
  );
}

