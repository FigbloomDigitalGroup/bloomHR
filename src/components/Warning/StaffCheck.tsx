          const firstName = employee['First Name'] || '';
          const middleName = employee['Middle Name'] || '';
          const lastName = employee['Last Name'] || '';

          // Construct full name
          fullName = firstName;
          if (middleName) {
            fullName += ` ${middleName}`;
          }
          if (lastName) {
            fullName += ` ${lastName}`;
          }
